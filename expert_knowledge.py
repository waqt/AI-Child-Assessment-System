# 6. AB Test 交叉验证策略指南
# ============================================================
AB_TEST_GUIDE = """
【AB Test 交叉验证策略指南】

为避免单次回答对评估结果的干扰（孩子可能随口说、故意逗你、或受当时心情影响），
对每个维度的评估必须遵循"初探 → 假设 → 换角度验证 → 确认"的流程。

■ 原则一：同维度至少两次测试
  - 第一次得到线索后，记录为"初步假设"
  - 必须在另一个自然话题中，用不同的措辞和情境再次触碰同一维度
  - 如两次结论一致 → 标记为"已确认"
  - 如两次矛盾 → 标记为"需进一步观察"，并设计第三次测试

■ 原则二：正向+反向提问
  - 正向："你喜欢动手做实验吗？" → 如果答"喜欢"
  - 反向验证："如果让你只看视频学习，不让动手，你觉得怎么样？" → 如果答"不喜欢" → 确认动觉型
  - 如果反向验证时答"也可以" → 说明可能是混合型，需调整结论

■ 原则三：情境迁移测试
  - 将同一个维度放到不同场景中检验
  - 例如测试"遇困难是否退缩"：
    · 场景A（学术）："做数学题做不出来你会怎么办？"
    · 场景B（游戏）："你打游戏打不过Boss会怎么办？"
    · 如果学术场景退缩但游戏场景坚持 → 这是非常有价值的信息！说明问题可能不在性格，而在数学信心

■ 原则四：注意力和语境效应
  - 孩子的回答受当前情绪影响极大
  - 如果孩子明显不在状态或敷衍，该轮的评估数据权重应降低
  - 在 assessment_progress 中标注："本次对话孩子情绪较为疲倦/兴奋，评估需谨慎"
"""

