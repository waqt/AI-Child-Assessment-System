def get_contextual_knowledge(conversation_context: str, top_k: int = 8) -> str:
    """
    根据当前对话上下文，从知识库中检索最相关的专业理论片段。
    使用 TF-IDF RAG 检索，仅返回与当前话题相关的知识。
    
    Args:
        conversation_context: 最近几轮对话的文本拼接
        top_k: 返回的最大片段数
        
    Returns:
        str: 拼接后的相关知识文本
    """
    try:
        from knowledge_rag import get_retriever
        retriever = get_retriever()
        results = retriever.retrieve(conversation_context, top_k=top_k)
        
        if not results:
            return ""
        
        parts = []
        for r in results:
            parts.append(r["text"])
        
        return "\n\n---\n\n".join(parts)
    except Exception as e:
        print(f"[KnowledgeRAG] Retrieval error: {e}")
        return ""


def get_full_knowledge_base(conversation_context: str = "") -> str:
    """
    Returns the expert knowledge base for injection into system prompt.
    
    If conversation_context is provided, uses RAG to retrieve only relevant
    professional theories. Core strategies are always included.
    
    Args:
        conversation_context: Recent conversation text for contextual retrieval
    """
    parts = [
        "=" * 60,
        "【第一部分：核心评估策略（必须遵守）】",
        "=" * 60,
        AB_TEST_GUIDE,
        ANTI_DECEPTION_GUIDE,
        SCENARIO_BANK,
    ]
    
    # RAG 检索相关专业理论
    if conversation_context:
        relevant_knowledge = get_contextual_knowledge(conversation_context, top_k=8)
        if relevant_knowledge:
            parts.extend([
                "\n" + "=" * 60,
                "【第二部分：与当前对话相关的专业理论（RAG 检索）】",
                "=" * 60,
                relevant_knowledge,
            ])
    
    # 如果没有上下文或 RAG 失败，回退到基础理论
    if not conversation_context:
        parts.extend([
            "\n" + "=" * 60,
            "【第二部分：基础评估框架】",
            "=" * 60,
            HIPIC_THEORY,
            DEVELOPMENT_THEORY,
            VARK_THEORY,
            GROWTH_MINDSET_THEORY,
            RESILIENCE_THEORY,
            BIG_FIVE_THEORY,
            MATH_ASSESSMENT_FRAMEWORK,
        ])
    
    return "\n\n".join(parts)

