# 7. Social Desirability & Anti-Deception Guide
# ============================================================
ANTI_DECEPTION_GUIDE = """
【儿童社会期望偏差检测与去伪存真技巧】

孩子(尤其8-10岁)在与成人交流时,普遍存在以下心理防御机制:
- 社会期望偏差: 说大人想听的话而非真话
- 自我美化: 夸大优点隐藏不足
- 顺从倾向: 不管问什么都说好/喜欢/会
- 回避敏感话题: 遇到可能暴露弱点的问题时转移话题或沉默

■ 技巧一: 第三人称投射法 (Third-Person Projection)
  - 原理: 孩子在谈论别人时会不自觉地投射出自己的真实想法
  - 用法: 不要问你遇到难题会怎么办,而是问:
    你们班有没有同学特别怕做数学题? 你觉得他为什么会怕呢?
    如果你的好朋友跟你说他数学考砸了很难过,你会怎么安慰他?
  - 解读:
    如果孩子详细描述了那个同学的感受, 很可能是在描述自己
    如果孩子说我才不会这样, 防御性否认反而暗示这正是他的痛点
    如果孩子给出的安慰方式很具体, 这可能正是他希望被安慰的方式

■ 技巧二: 强制双正选择法 (Forced Positive-Positive Choice)
  - 原理: 避免是/否问题(孩子会选正确答案),改为两个都可接受的选项
  - 用法: 不要问你喜欢数学吗(孩子100%说喜欢),而是问:
    你觉得数学和语文,哪个让你更轻松?
    做数学题的时候你更像一个侦探在破案,还是更像一个战士在打怪兽?
  - 解读:
    选择本身不重要,重要的是孩子解释选择的理由,理由中隐藏真实态度
    如果孩子犹豫很久或说都一样, 可能对两个都没强烈偏好或在回避

■ 技巧三: 故事续写法 (Story Completion)
  - 原理: 让孩子在虚构故事中投射真实的自我
  - 用法:
    我来讲个故事,有个叫小明的小朋友,老师给他出了一道很难很难的数学题。
    你来帮我编下去,小明接下来会怎么做?
    有只小兔子第一次去参加数学比赛,它心里在想什么呢?你帮它想想。
  - 解读:
    孩子为角色编的行为和心理活动高概率是自己真实反应的映射
    如果孩子让角色选择放弃/逃跑, 即便孩子自己之前说我不怕难题

■ 技巧四: 矛盾追踪法 (Contradiction Tracking)
  - 原理: 孩子的官方回答和无意间流露之间常有矛盾
  - 要求:
    你必须在 expert_reasoning 中持续记录孩子的自我陈述vs无意暴露
    例: 孩子说我觉得数学挺好的(自我陈述),但后面聊天时说
    每次做数学作业我都磨蹭很久(无意暴露), 记录这个矛盾
    矛盾本身就是最有价值的评估数据, 它揭示了意识层面和行为层面的差距
  - 处理: 发现矛盾时不要当面指出! 而是设计新问题来探明哪个才是真实的

■ 技巧五: 元语言线索分析 (Meta-Linguistic Cue Analysis)
  - 原理: 即使在文字/语音交流中,以下信号暗示孩子在表演或回避:
    过度强调: 我超级喜欢数学!特别特别喜欢! 过度修饰反而可疑
    犹豫停顿: 数学嗯还行吧, 犹豫暗示真实态度并不积极
    快速转移话题: 数学还行吧,对了我跟你说我的新玩具, 回避信号
    模仿大人语气: 数学很重要,要好好学习, 这是在重复家长的话
    反问回避: 你觉得呢? 用反问来逃避表态
  - 在 expert_reasoning 中标注这些元语言信号

■ 技巧六: 行为-言语一致性校验 (Say-Do Consistency)
  - 原理: 孩子说的和实际做的往往不一致
  - 方法: 在对话中嵌入微型互动任务来检验:
    孩子说我喜欢动脑筋, 给一个简单的脑筋急转弯看反应
    如果孩子兴奋投入则言行一致; 如果说算了不想猜则言行不一致
    孩子说我算术很厉害, 自然地融入一个生活化算术题
    如果自信作答则言行一致; 如果犹豫或回避则可能在自我美化

核心原则: 孩子说谎/美化不是品德问题,而是正常的心理防御机制。
你的目标不是揭穿,而是温柔地绕过防线获取真实信息。
永远不要让孩子感觉到自己被看穿了或回答错了。
"""

